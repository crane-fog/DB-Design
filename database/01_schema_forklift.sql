-- ============================================================================
-- 为 external_order.status 添加 "已转换" 状态
-- 原因：外部订单审核接受后转为生产订单时，需要标记为已转换以区分"待转换"和"已转换"。
-- ============================================================================

BEGIN
  -- 同时清理命名约束和旧版自动命名约束；旧约束条件可能以小写 status 保存。
  FOR status_constraint IN (
    SELECT constraint_name
    FROM user_constraints
     WHERE table_name = 'EXTERNAL_ORDER'
       AND constraint_type = 'C'
       AND (
         constraint_name = 'CK_EXTERNAL_ORDER_STATUS'
         OR UPPER(REPLACE(search_condition_vc, '"', '')) LIKE '%STATUS%IN%'
       )
  ) LOOP
    EXECUTE IMMEDIATE
      'ALTER TABLE external_order DROP CONSTRAINT ' || status_constraint.constraint_name;
  END LOOP;
END;
/

ALTER TABLE external_order ADD CONSTRAINT ck_external_order_status
  CHECK (status IN ('待审核','已接受','已拒绝','已转换'));

COMMIT;
